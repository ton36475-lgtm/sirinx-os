  /**
   * Normalize a string for search: lowercase, remove tones, collapse spaces.
   */
  function normalize(str) {
    return str
      .toLowerCase()
      .replace(/[\u0E31\u0E34-\u0E3A\u0E47-\u0E4E]/g, '') // strip Thai tone marks
      .replace(/[^a-zA-Z0-9\u0E00-\u0E7F\s]/g, ' ')
      .replace(/\s+/g, ' ')
      .trim();
  }

  /**
   * Score a query against an industry entry.
   * Returns number of keywords matched (higher = better).
   */
  function scoreIndustry(query, entry) {
    var qNorm = normalize(query);
    var tokens = qNorm.split(' ');
    var score = 0;
    var matched = {};
    for (var i = 0; i < tokens.length; i++) {
      var token = tokens[i];
      if (token.length < 2) continue;
      for (var k = 0; k < entry.keywords.length; k++) {
        var kw = normalize(entry.keywords[k]);
        if (kw.indexOf(token) !== -1 && !matched[kw]) {
          score += (kw === token) ? 3 : 1;
          matched[kw] = true;
        }
      }
    }
    // bonus if query contains the industry's English or Thai name
    var nameEnNorm = normalize(entry.nameEn);
    var nameThNorm = normalize(entry.nameTh);
    var qLower = query.toLowerCase();
    if (qLower.indexOf(entry.nameEn.toLowerCase()) !== -1) score += 5;
    if (qLower.indexOf(entry.nameTh.toLowerCase()) !== -1) score += 5;
    return score;
  }

  /**
   * Return the best-matching industry entry for a free-text query,
   * or null if no meaningful match.
   */
  function getKnowledgeForQuery(query) {
    if (!query || query.trim().length < 2) return null;

    var best = null;
    var bestScore = 0;

    for (var i = 0; i < DATA.length; i++) {
      var score = scoreIndustry(query, DATA[i]);
      if (score > bestScore) {
        bestScore = score;
        best = DATA[i];
      }
    }

    return bestScore > 0 ? best : null;
  }

  // Export as global
  window.SIRINX_KNOWLEDGE = {
    industries: DATA,
    getKnowledgeForQuery: getKnowledgeForQuery
  };

